const assert=require('node:assert/strict');
const O=require('../dist/paper-outline.js');
const get=(c,l)=>O.panelText(c).get(l)?.text;
const c1='Figure 2: The role of affinities in t-SNE. MNIST data set. (a) Default t-SNE, Gaussian affinities, perplexity 30. (b) t-SNE with binary kNN affinities: all nonzero pij are the same.';
assert.equal(get(c1,'a'),'Default t-SNE, Gaussian affinities, perplexity 30');
assert.equal(get(c1,'b'),'t-SNE with binary kNN affinities: all nonzero pij are the same');
assert.equal(O.title(c1,'Figure 2'),'The role of affinities in t-SNE');
const c2='Figure 5: Simulated data. Panels (b–f) used a shared random initialization. Panels (b–d) did not.';
assert.equal(get(c2,'a'),undefined,'no description is invented');
assert.equal(get(c2,'b'),undefined,'a fragment of "Panels (b–f) used…" is not a description');
assert.deepEqual(O.panelText('Figure 1: Data. (a–c) Three groups of mice.').get('b').shared,['a','b','c']);
const c3='Fig. 1 | Overview. a, Study design for mice. b, Survival curves over time. c, d, e';
assert.equal(get(c3,'a'),'Study design for mice');
assert.equal(get(c3,'c'),undefined);
assert.equal(get('Figure 9: Values shown in (a) and (b) are means.','a'),undefined);
assert.equal(O.claim('Here we empirically show that changing the balance yields a spectrum.'),'Changing the balance yields a spectrum.');
const r=(text,mentions=[])=>({text,mentions});
const rows=[r('1. Introduction'),r('See Figure 1.',['F:1']),r('2. Methods'),r('12 Mice were used.'),r('3. Results'),r('3.1 First result'),r('Figure 1 and Figure 2 show it.',['F:1','F:2']),r('4. Discussion of limits'),r('Figure 3 is discussed.',['F:3']),r('References'),r('5. Smith A. Title')];
const figs=['F:1','F:2','F:3'].map(matchKey=>({matchKey}));
assert.deepEqual(O.sections(rows,figs).map(s=>[s.number,s.figures.length]),[['3',2],['4',1]]);
